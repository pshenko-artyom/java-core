package org.pshenko.javacore.basics;

public class IfElseLesson {
    public static void main(String[] args) {
        int num = 1;

        if(num == 0) {
            System.out.println("num is 0");
        } else if (num > 0) {
            System.out.println("num is more than 0");
        } else  {
            System.out.println("num is less than 0");
        }
    }
}
