package org.pshenko.javacore.basics;

public class LoopsLesson {
    public static void main(String[] args) {
        for (int i = 0; i <= 10; i++) {
            System.out.println(i);
        }

        System.out.println("===============");
        
        int i = 10;
        while (i > 0) {
            System.out.println(i);
            i--;
        }
    }
}
